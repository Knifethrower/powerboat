#!/usr/bin/env python3
"""Xcursor files -> powerboat/js/86c_cursors.js: the default pointers of HTML pages as PNG data URLs with their
hotspots (one nominal size). Source: GNOME's Adwaita cursor theme (CC-BY-SA-3.0 or LGPL-3, and CC-BY-SA-4.0;
attribution "GNOME Project"), licenses/adwaita-cursors.txt.
    python3 tools/xcursor_to_js.py /usr/share/icons/Adwaita/cursors [size, default 24] [--black]
White by default: Adwaita's black pointers with their colors inverted (white fill, black outline), the soft
shadow kept; --black keeps the originals.
"""
import base64, io, os, struct, sys
from PIL import Image

src = sys.argv[1]
args = [a for a in sys.argv[2:] if not a.startswith("--")]
want = int(args[0]) if args else 24
white = "--black" not in sys.argv
NAMES = {"arrow": "default", "hand": "pointer", "text": "text", "wait": "wait", "grab": "grab", "not-allowed": "not-allowed"}

def read(path):
    d = open(path, "rb").read()
    assert d[:4] == b"Xcur", path
    hsize, version, ntoc = struct.unpack_from("<III", d, 4)
    best = None
    for i in range(ntoc):
        typ, sub, pos = struct.unpack_from("<III", d, hsize + i * 12)
        if typ != 0xFFFD0002:
            continue
        csize, ctype, nominal, cver, w, h, xhot, yhot, delay = struct.unpack_from("<IIIIIIIII", d, pos)
        if best is None or abs(nominal - want) < abs(best[0] - want):
            best = (nominal, w, h, xhot, yhot, pos + csize)
    nominal, w, h, xhot, yhot, off = best
    px = d[off: off + w * h * 4]
    im = Image.new("RGBA", (w, h))
    out = []
    for i in range(w * h):
        b, g, r, a = px[i * 4: i * 4 + 4]  # little-endian ARGB, premultiplied
        if a:
            r, g, b = min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a)
        # White variant: solid pixels and the outline's light edge invert; the shadow (dark, see-through) stays.
        if white and a and (a > 200 or (r + g + b) > 384):
            r, g, b = 255 - r, 255 - g, 255 - b
        out.append((r, g, b, a))
    im.putdata(out)
    buf = io.BytesIO(); im.save(buf, "PNG", optimize=True)
    return w, h, xhot, yhot, base64.b64encode(buf.getvalue()).decode()

lines = ["// powerboat JS environment, part 9b3: default pointers for HTML pages (87_paint.js draws them).",
         "// GNOME's Adwaita cursor theme" + (", colors inverted (white)" if white else "") + ", made by GNOME Project; CC-BY-SA-3.0 or LGPL-3, and CC-BY-SA-4.0",
         "// (licenses/adwaita-cursors.txt). Generated by tools/xcursor_to_js.py; do not edit.",
         '"use strict";',
         "__powerboat.defaultCursors = {"]
for key, name in NAMES.items():
    w, h, x, y, b64 = read(os.path.join(src, name))
    lines.append(f'  "{key}": {{ w: {w}, h: {h}, hot: [{x}, {y}], src: "data:image/png;base64,{b64}" }},')
lines.append("};")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "powerboat", "js", "86c_cursors.js")
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote", out, os.path.getsize(out), "bytes")
